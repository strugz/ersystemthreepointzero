-- =====================================================================
--  ERFWeb — job grades as master data (028_job_grades.sql)
--  The System Administrator keeps the list on Master data -> Job grades. Users and Grade rate
--  assignments store the code (users.job_grade, rate_profile_assignments.job_grade); the label is
--  shown on screen. A code never changes once created; a grade is deactivated, never deleted.
--  Seeds the first three grades. Older free-text grades in users / rate_profile_assignments are not
--  changed by this script; fix them on the Users and Rate profiles pages.
--  Idempotent: safe to re-run. Run after 001..027, BEFORE deploying the API that needs it.
-- =====================================================================
BEGIN;

CREATE TABLE IF NOT EXISTS job_grades (
  id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code      character varying(32)  NOT NULL,
  name      character varying(200) NOT NULL,
  is_active boolean NOT NULL DEFAULT true
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_job_grades_code ON job_grades (code);

INSERT INTO job_grades (code, name) VALUES
  ('Staff', 'Staff'),
  ('Specialist', 'Specialists/Engineers'),
  ('Supervisor', 'Team Leaders/Supervisors/Assistant Managers')
ON CONFLICT (code) DO NOTHING;

INSERT INTO schema_versions (version, name) VALUES (28, '028_job_grades')
ON CONFLICT (version) DO NOTHING;

COMMIT;

