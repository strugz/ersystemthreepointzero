-- =====================================================================
--  ERFWeb — cash advances become lines (005_cash_advance_lines.sql)
--  The R47 "CASH ADVANCE RECEIVED" block is a table with a TOTAL row, so a report may
--  record several advances. This replaces the one-row cash_advances table with
--  cash_advance_lines, copies any existing advance across, and moves the history
--  trigger. Idempotent: safe to re-run.
-- =====================================================================
BEGIN;

CREATE TABLE IF NOT EXISTS cash_advance_lines (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id          uuid        NOT NULL REFERENCES expense_reports(id) ON DELETE CASCADE,
  advance_date       date,
  reference_document varchar(100),
  reference_no       varchar(50),
  amount             numeric(14,2) NOT NULL DEFAULT 0,
  sort_order         integer     NOT NULL DEFAULT 0,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_cash_advance_lines_report_id_sort_order ON cash_advance_lines (report_id, sort_order);

-- Carry over existing single advances (only those that actually hold an amount).
INSERT INTO cash_advance_lines (report_id, advance_date, reference_document, reference_no, amount, sort_order)
SELECT ca.report_id, ca.advance_date, ca.reference_document, ca.reference_no, ca.amount, 1
FROM cash_advances ca
WHERE ca.amount > 0
  AND NOT EXISTS (SELECT 1 FROM cash_advance_lines l WHERE l.report_id = ca.report_id);

-- Row history: cash advances are edited by employees while drafting, so they stay tracked.
DROP TRIGGER IF EXISTS trg_hist_cash_advances ON cash_advances;
DROP TRIGGER IF EXISTS trg_hist_cash_advance_lines ON cash_advance_lines;
CREATE TRIGGER trg_hist_cash_advance_lines AFTER UPDATE OR DELETE ON cash_advance_lines
  FOR EACH ROW EXECUTE FUNCTION fn_record_history('id');

DROP TABLE IF EXISTS cash_advances;

COMMIT;
