-- =====================================================================
--  ERFWeb — Phase 2: scope assignments and rate profiles (007_scope_and_rate_profiles.sql)
--  RBAC v0.6 sections 4 and 5, maintained by Level 2 only.
--   * scope_assignments (+ members) replace approval_routes: filing now resolves the approvers
--     from scope and snapshots them into approval_steps (approval_steps.signatory_level added).
--   * rate_profiles / rate_profile_lines / rate_profile_assignments replace employee_rates:
--     effective-dated, versioned, resolved Individual > Grade > Department > Company on the
--     expense date.
--  Existing approval_routes and employee_rates rows are copied across as bootstrap records owned
--  by the first System Administrator. The old tables are kept (unused) so the rollback below works.
--  Idempotent: safe to re-run. Run after 001..006.
-- =====================================================================
BEGIN;

-- ---------- Scope ----------
CREATE TABLE IF NOT EXISTS scope_assignments (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  holder_user_id     bigint NOT NULL REFERENCES users (id),
  signatory_level    smallint NOT NULL CHECK (signatory_level IN (1, 2)),
  assignment_type    character varying(16) NOT NULL,      -- Department | Individual | Exclusion
  department_id      bigint REFERENCES departments (id),
  approval_limit     numeric(14,2),                        -- NULL = no limit; above it a Level 2 step is added
  effective_from     date NOT NULL DEFAULT current_date,
  effective_to       date,
  is_active          boolean NOT NULL DEFAULT true,
  is_bootstrap       boolean NOT NULL DEFAULT false,
  note               character varying(500),
  created_by_user_id bigint NOT NULL REFERENCES users (id),
  created_at         timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT ck_scope_no_self_scope  CHECK (created_by_user_id <> holder_user_id),                 -- 9.13
  CONSTRAINT ck_scope_type           CHECK (assignment_type IN ('Department', 'Individual', 'Exclusion')),
  CONSTRAINT ck_scope_department     CHECK ((assignment_type = 'Individual') = (department_id IS NULL)),
  CONSTRAINT ck_scope_dates          CHECK (effective_to IS NULL OR effective_to >= effective_from)
);
CREATE INDEX IF NOT EXISTS ix_scope_assignments_holder_user_id           ON scope_assignments (holder_user_id);
CREATE INDEX IF NOT EXISTS ix_scope_assignments_department_id_signatory  ON scope_assignments (department_id, signatory_level);
CREATE INDEX IF NOT EXISTS ix_scope_assignments_created_by_user_id       ON scope_assignments (created_by_user_id);

CREATE TABLE IF NOT EXISTS scope_assignment_members (
  scope_assignment_id bigint NOT NULL REFERENCES scope_assignments (id) ON DELETE CASCADE,
  user_id             bigint NOT NULL REFERENCES users (id),
  PRIMARY KEY (scope_assignment_id, user_id)
);
CREATE INDEX IF NOT EXISTS ix_scope_assignment_members_user_id ON scope_assignment_members (user_id);

ALTER TABLE approval_steps ADD COLUMN IF NOT EXISTS signatory_level smallint;

-- ---------- Rate profiles ----------
CREATE TABLE IF NOT EXISTS rate_profiles (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name               character varying(200) NOT NULL,
  is_active          boolean NOT NULL DEFAULT true,
  created_by_user_id bigint NOT NULL REFERENCES users (id),
  created_at         timestamp with time zone NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_rate_profiles_name               ON rate_profiles (name);
CREATE INDEX        IF NOT EXISTS ix_rate_profiles_created_by_user_id ON rate_profiles (created_by_user_id);

-- One row per category (and meal) per version. A change closes the open row and inserts a new one.
CREATE TABLE IF NOT EXISTS rate_profile_lines (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rate_profile_id    bigint NOT NULL REFERENCES rate_profiles (id) ON DELETE CASCADE,
  category           character varying(24) NOT NULL,      -- Meals | Transportation | Toll | Parking | Others | Representation
  sub_category       character varying(32),               -- Meals: Breakfast | Lunch | Dinner | OTMeal
  rate_type          character varying(24) NOT NULL,      -- FixedPerDay | PerKm | CapPerTransaction | ActualWithCeiling
  amount             numeric(14,2) NOT NULL CHECK (amount >= 0),
  currency           character varying(3) NOT NULL DEFAULT 'PHP',
  frequency_cap      integer CHECK (frequency_cap IS NULL OR frequency_cap >= 1),
  requires_receipt   boolean NOT NULL DEFAULT true,
  effective_from     date NOT NULL,
  effective_to       date,
  changed_by_user_id bigint NOT NULL REFERENCES users (id),
  change_reason      character varying(500),
  backdate_override  boolean NOT NULL DEFAULT false,
  created_at         timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT ck_rate_lines_dates CHECK (effective_to IS NULL OR effective_to >= effective_from)
);
CREATE INDEX IF NOT EXISTS ix_rate_profile_lines_key                ON rate_profile_lines (rate_profile_id, category, sub_category, effective_from);
CREATE INDEX IF NOT EXISTS ix_rate_profile_lines_changed_by_user_id ON rate_profile_lines (changed_by_user_id);

CREATE TABLE IF NOT EXISTS rate_profile_assignments (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rate_profile_id     bigint NOT NULL REFERENCES rate_profiles (id),
  target_type         character varying(16) NOT NULL,     -- Individual | Grade | Department | Company
  user_id             bigint REFERENCES users (id),
  job_grade           character varying(32),
  department_id       bigint REFERENCES departments (id),
  effective_from      date NOT NULL DEFAULT current_date,
  effective_to        date,
  is_bootstrap        boolean NOT NULL DEFAULT false,
  change_reason       character varying(500),
  assigned_by_user_id bigint NOT NULL REFERENCES users (id),
  assigned_at         timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT ck_rate_assign_no_self_rate CHECK (user_id IS DISTINCT FROM assigned_by_user_id),   -- 9.12
  CONSTRAINT ck_rate_assign_dates        CHECK (effective_to IS NULL OR effective_to >= effective_from),
  CONSTRAINT ck_rate_assign_target CHECK (
    (target_type = 'Individual' AND user_id IS NOT NULL AND job_grade IS NULL AND department_id IS NULL) OR
    (target_type = 'Grade'      AND job_grade IS NOT NULL AND user_id IS NULL AND department_id IS NULL) OR
    (target_type = 'Department' AND department_id IS NOT NULL AND user_id IS NULL AND job_grade IS NULL) OR
    (target_type = 'Company'    AND user_id IS NULL AND job_grade IS NULL AND department_id IS NULL))
);
CREATE INDEX IF NOT EXISTS ix_rate_profile_assignments_target              ON rate_profile_assignments (target_type, user_id, job_grade, department_id);
CREATE INDEX IF NOT EXISTS ix_rate_profile_assignments_rate_profile_id     ON rate_profile_assignments (rate_profile_id);
CREATE INDEX IF NOT EXISTS ix_rate_profile_assignments_user_id             ON rate_profile_assignments (user_id);
CREATE INDEX IF NOT EXISTS ix_rate_profile_assignments_department_id       ON rate_profile_assignments (department_id);
CREATE INDEX IF NOT EXISTS ix_rate_profile_assignments_assigned_by_user_id ON rate_profile_assignments (assigned_by_user_id);

-- ---------- Row history on the entitlement tables ----------
DROP TRIGGER IF EXISTS trg_hist_scope_assignments        ON scope_assignments;
DROP TRIGGER IF EXISTS trg_hist_rate_profile_lines       ON rate_profile_lines;
DROP TRIGGER IF EXISTS trg_hist_rate_profile_assignments ON rate_profile_assignments;
CREATE TRIGGER trg_hist_scope_assignments        AFTER UPDATE OR DELETE ON scope_assignments
  FOR EACH ROW EXECUTE FUNCTION fn_record_history('id');
CREATE TRIGGER trg_hist_rate_profile_lines       AFTER UPDATE OR DELETE ON rate_profile_lines
  FOR EACH ROW EXECUTE FUNCTION fn_record_history('id');
CREATE TRIGGER trg_hist_rate_profile_assignments AFTER UPDATE OR DELETE ON rate_profile_assignments
  FOR EACH ROW EXECUTE FUNCTION fn_record_history('id');

-- ---------- Carry over the fixed routes and flat rates ----------
DO $$
DECLARE
  v_admin bigint;
BEGIN
  SELECT u.id INTO v_admin
  FROM users u JOIN user_roles r ON r.user_id = u.id
  WHERE r.role = 'SystemAdministrator' AND r.status = 'Active'
  ORDER BY u.id LIMIT 1;

  IF v_admin IS NULL THEN
    RAISE NOTICE '007: no active System Administrator; existing routes and rates were not migrated.';
    RETURN;
  END IF;

  -- approval_routes: step 1 becomes a Level 1 by-name assignment, later steps Level 2.
  -- One assignment per approver and level, naming every employee routed to them.
  IF NOT EXISTS (SELECT 1 FROM scope_assignments WHERE note = 'Migrated from approval_routes by 007') THEN
    INSERT INTO scope_assignments (holder_user_id, signatory_level, assignment_type, department_id,
                                   effective_from, is_bootstrap, note, created_by_user_id)
    SELECT DISTINCT ar.approver_user_id, CASE WHEN ar.step_order = 1 THEN 1 ELSE 2 END, 'Individual', NULL::bigint,
                    current_date, true, 'Migrated from approval_routes by 007', v_admin
    FROM approval_routes ar
    WHERE ar.approver_user_id <> v_admin;

    INSERT INTO scope_assignment_members (scope_assignment_id, user_id)
    SELECT DISTINCT sa.id, ar.employee_user_id
    FROM approval_routes ar
    JOIN scope_assignments sa
      ON sa.holder_user_id = ar.approver_user_id
     AND sa.signatory_level = CASE WHEN ar.step_order = 1 THEN 1 ELSE 2 END
     AND sa.note = 'Migrated from approval_routes by 007'
    WHERE ar.employee_user_id <> ar.approver_user_id
    ON CONFLICT DO NOTHING;
  END IF;

  -- employee_rates: one personal profile per employee, in force since 2000-01-01 so older ERFs resolve too.
  INSERT INTO rate_profiles (name, created_by_user_id)
  SELECT 'Migrated - ' || u.username, v_admin
  FROM employee_rates er JOIN users u ON u.id = er.user_id
  WHERE u.id <> v_admin
  ON CONFLICT (name) DO NOTHING;

  INSERT INTO rate_profile_lines (rate_profile_id, category, sub_category, rate_type, amount, requires_receipt,
                                  effective_from, changed_by_user_id, change_reason)
  SELECT p.id, x.category, x.sub_category, 'FixedPerDay', x.amount, false, DATE '2000-01-01', v_admin,
         'Migrated from employee_rates by 007'
  FROM employee_rates er
  JOIN users u ON u.id = er.user_id
  JOIN rate_profiles p ON p.name = 'Migrated - ' || u.username
  CROSS JOIN LATERAL (VALUES
      ('Transportation', NULL,        er.transport_rate),
      ('Meals',          'Breakfast', er.breakfast_rate),
      ('Meals',          'Lunch',     er.lunch_rate),
      ('Meals',          'Dinner',    er.dinner_rate),
      ('Meals',          'OTMeal',    er.ot_meal_rate)) AS x(category, sub_category, amount)
  WHERE x.amount > 0
    AND NOT EXISTS (SELECT 1 FROM rate_profile_lines l WHERE l.rate_profile_id = p.id);

  INSERT INTO rate_profile_assignments (rate_profile_id, target_type, user_id, effective_from, is_bootstrap,
                                        change_reason, assigned_by_user_id)
  SELECT p.id, 'Individual', u.id, DATE '2000-01-01', true, 'Migrated from employee_rates by 007', v_admin
  FROM employee_rates er
  JOIN users u ON u.id = er.user_id
  JOIN rate_profiles p ON p.name = 'Migrated - ' || u.username
  WHERE u.id <> v_admin
    AND NOT EXISTS (SELECT 1 FROM rate_profile_assignments a WHERE a.rate_profile_id = p.id);
END $$;

COMMIT;

