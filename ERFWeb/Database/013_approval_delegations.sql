-- =====================================================================
--  ERFWeb — Phase 7: approval delegation (013_approval_delegations.sql)
--  * approval_delegations: a signatory names a delegate of the same level or higher for a date
--    range; the delegate approves in their place while it is in force. A Level 2 may assign one
--    for an absent Level 1 (is_forced). Only approving is delegated; rates and scope never are.
--    Overlap and level checks are enforced by the service in a serializable transaction.
--  * approval_steps.acted_by_user_id records who actually acted on a step, and delegation_id the
--    delegation they acted under, so the step reads "by [Delegate] on behalf of [Signatory]".
--  * Row history through the existing fn_record_history trigger.
--  Idempotent: safe to re-run. Run after 001..012.
-- =====================================================================
BEGIN;

CREATE TABLE IF NOT EXISTS approval_delegations (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  signatory_user_id     bigint NOT NULL REFERENCES users (id),
  delegate_user_id      bigint NOT NULL REFERENCES users (id),
  starts_on             date   NOT NULL,
  ends_on               date   NOT NULL,
  reason                character varying(1000),
  is_forced             boolean NOT NULL DEFAULT false,   -- assigned by the Level 2 for an absent Level 1
  created_by_user_id    bigint NOT NULL REFERENCES users (id),
  created_at            timestamp with time zone NOT NULL DEFAULT now(),
  cancelled_by_user_id  bigint REFERENCES users (id),
  cancelled_at          timestamp with time zone,
  updated_at            timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT ck_approval_delegations_dates    CHECK (ends_on >= starts_on),
  CONSTRAINT ck_approval_delegations_not_self CHECK (delegate_user_id <> signatory_user_id)
);

CREATE INDEX IF NOT EXISTS ix_approval_delegations_signatory_user_id    ON approval_delegations (signatory_user_id);
CREATE INDEX IF NOT EXISTS ix_approval_delegations_delegate_user_id     ON approval_delegations (delegate_user_id);
CREATE INDEX IF NOT EXISTS ix_approval_delegations_created_by_user_id   ON approval_delegations (created_by_user_id);
CREATE INDEX IF NOT EXISTS ix_approval_delegations_cancelled_by_user_id ON approval_delegations (cancelled_by_user_id);

DROP TRIGGER IF EXISTS trg_hist_approval_delegations ON approval_delegations;
CREATE TRIGGER trg_hist_approval_delegations AFTER UPDATE OR DELETE ON approval_delegations
  FOR EACH ROW EXECUTE FUNCTION fn_record_history('id');

ALTER TABLE approval_steps ADD COLUMN IF NOT EXISTS acted_by_user_id bigint REFERENCES users (id);
ALTER TABLE approval_steps ADD COLUMN IF NOT EXISTS delegation_id    bigint REFERENCES approval_delegations (id);
CREATE INDEX IF NOT EXISTS ix_approval_steps_acted_by_user_id ON approval_steps (acted_by_user_id);
CREATE INDEX IF NOT EXISTS ix_approval_steps_delegation_id    ON approval_steps (delegation_id);

COMMIT;

