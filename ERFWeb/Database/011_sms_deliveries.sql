-- =====================================================================
--  ERFWeb — notification SMS through the Lasius gateway (011_sms_deliveries.sql)
--  * sms_deliveries: one row per notification SMS. The unique (sender_user_id, idempotency_key)
--    pair is claimed before the gateway is called, so a retried request never texts twice.
--  * The message text and phone numbers are NOT stored; only a SHA-256 of the message, to refuse a
--    key reused for a different message.
--  * Status: Sending -> Sent | Failed (gateway refused; may be retried) | Unconfirmed (no answer;
--    never resent under the same key).
--  Idempotent: safe to re-run. Run after 001..010.
-- =====================================================================
BEGIN;

CREATE TABLE IF NOT EXISTS sms_deliveries (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_user_id       bigint NOT NULL REFERENCES users (id),
  idempotency_key      character varying(100) NOT NULL,
  recipient_user_id    bigint NOT NULL REFERENCES users (id),
  recipient_count      integer NOT NULL,
  message_sha256       character(64) NOT NULL,
  status               character varying(16) NOT NULL,                -- Sending | Sent | Failed | Unconfirmed
  gateway_http_status  integer,
  attempts             integer NOT NULL DEFAULT 1,
  created_at           timestamp with time zone NOT NULL DEFAULT now(),
  completed_at         timestamp with time zone
);

CREATE UNIQUE INDEX IF NOT EXISTS ix_sms_deliveries_sender_user_id_idempotency_key
  ON sms_deliveries (sender_user_id, idempotency_key);
CREATE INDEX IF NOT EXISTS ix_sms_deliveries_recipient_user_id ON sms_deliveries (recipient_user_id);

COMMIT;

