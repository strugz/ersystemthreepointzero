-- =====================================================================
--  ERFWeb — fare modes on transportation fare legs (016_fare_modes.sql)
--  * fare_modes: how a fare leg was travelled (Taxi, Grab, Angkas, Jeepney, ...). Maintained by the
--    System Administrator under Master data; rows are deactivated, never deleted, because legs
--    reference them. Replaces the legacy dbo.tbFare list, where any user could add a type; here
--    employees pick "Others" and type the mode instead (requires_detail).
--  * receipt_expected is recorded for Finance but not enforced yet.
--  * expense_transport_items.fare_mode_id / fare_mode_detail: nullable, so legs saved before this
--    script stay valid ("Not specified"); the API requires a mode on every leg it saves from now on.
--  Idempotent: safe to re-run. Run after 001..015, BEFORE deploying the API that needs it.
-- =====================================================================
BEGIN;

CREATE TABLE IF NOT EXISTS fare_modes (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code              character varying(20)  NOT NULL,
  name              character varying(60)  NOT NULL,
  sort_order        integer                NOT NULL DEFAULT 0,
  receipt_expected  boolean                NOT NULL DEFAULT false,
  requires_detail   boolean                NOT NULL DEFAULT false,
  legacy_fare_id    integer,
  is_active         boolean                NOT NULL DEFAULT true,
  CONSTRAINT ux_fare_modes_code UNIQUE (code)
);

INSERT INTO fare_modes (code, name, sort_order, receipt_expected, requires_detail) VALUES
  ('TAXI',    'Taxi',                        10,  true,  false),
  ('GRAB',    'Grab / ride-hailing',         20,  true,  false),
  ('ANGKAS',  'Angkas / motorcycle taxi',    30,  true,  false),
  ('JEEP',    'Jeepney',                     40,  false, false),
  ('TRIKE',   'Tricycle',                    50,  false, false),
  ('PEDICAB', 'Pedicab',                     60,  false, false),
  ('BUS',     'Bus',                         70,  true,  false),
  ('UV',      'UV Express / van',            80,  false, false),
  ('RAIL',    'MRT / LRT / train',           90,  false, false),
  ('BOAT',    'Ferry / boat',                100, true,  false),
  ('HABAL',   'Habal-habal',                 110, false, false),
  ('OTHERS',  'Others (specify)',            999, false, true)
ON CONFLICT (code) DO NOTHING;

ALTER TABLE expense_transport_items
  ADD COLUMN IF NOT EXISTS fare_mode_id bigint,
  ADD COLUMN IF NOT EXISTS fare_mode_detail character varying(60);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_expense_transport_items_fare_modes_fare_mode_id') THEN
    ALTER TABLE expense_transport_items
      ADD CONSTRAINT fk_expense_transport_items_fare_modes_fare_mode_id
      FOREIGN KEY (fare_mode_id) REFERENCES fare_modes (id) ON DELETE RESTRICT;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS ix_expense_transport_items_fare_mode_id ON expense_transport_items (fare_mode_id);

INSERT INTO schema_versions (version, name) VALUES (16, '016_fare_modes')
ON CONFLICT (version) DO NOTHING;

COMMIT;

