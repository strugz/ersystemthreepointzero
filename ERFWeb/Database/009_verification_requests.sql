-- =====================================================================
--  ERFWeb — Phase 6: verification requests and queries (009_verification_requests.sql)
--  * verification_requests: Finance asks an Expense Verifier to fact-check one line of an
--    approved report (Flow 6). Status runs Open -> InProgress -> Found (Not Verified only) ->
--    Queried (to Level 2) -> Closed. A Verified finding closes it directly.
--  * One unresolved request per line (partial unique index); clearance waits until none are open.
--  * Row history through the existing fn_record_history trigger.
--  Idempotent: safe to re-run. Run after 001..008.
-- =====================================================================
BEGIN;

CREATE TABLE IF NOT EXISTS verification_requests (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id             uuid   NOT NULL REFERENCES expense_reports (id) ON DELETE CASCADE,
  expense_line_id       bigint NOT NULL REFERENCES expense_lines (id) ON DELETE CASCADE,
  reason                character varying(2000) NOT NULL,
  status                character varying(16)   NOT NULL DEFAULT 'Open',   -- Open | InProgress | Found | Queried | Closed
  requested_by_user_id  bigint NOT NULL REFERENCES users (id),
  requested_at          timestamp with time zone NOT NULL DEFAULT now(),
  verifier_user_id      bigint REFERENCES users (id),
  picked_up_at          timestamp with time zone,
  finding               character varying(24),                            -- Verified | VerifiedWithNote | NotVerified
  finding_note          character varying(2000),
  found_at              timestamp with time zone,
  query_to_user_id      bigint REFERENCES users (id),
  queried_by_user_id    bigint REFERENCES users (id),
  query_note            character varying(2000),
  queried_at            timestamp with time zone,
  disposition           character varying(16),                            -- Resume | Return | Reject
  disposition_note      character varying(2000),
  decided_by_user_id    bigint REFERENCES users (id),
  decided_at            timestamp with time zone,
  closed_at             timestamp with time zone,
  created_at            timestamp with time zone NOT NULL DEFAULT now(),
  updated_at            timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_verification_requests_report_id          ON verification_requests (report_id);
CREATE INDEX IF NOT EXISTS ix_verification_requests_status             ON verification_requests (status);
CREATE INDEX IF NOT EXISTS ix_verification_requests_verifier_user_id   ON verification_requests (verifier_user_id);
CREATE INDEX IF NOT EXISTS ix_verification_requests_query_to_user_id   ON verification_requests (query_to_user_id);
CREATE INDEX IF NOT EXISTS ix_verification_requests_requested_by_user_id ON verification_requests (requested_by_user_id);
CREATE INDEX IF NOT EXISTS ix_verification_requests_queried_by_user_id ON verification_requests (queried_by_user_id);
CREATE INDEX IF NOT EXISTS ix_verification_requests_decided_by_user_id ON verification_requests (decided_by_user_id);
CREATE UNIQUE INDEX IF NOT EXISTS ix_verification_requests_expense_line_id
  ON verification_requests (expense_line_id) WHERE status <> 'Closed';

DROP TRIGGER IF EXISTS trg_hist_verification_requests ON verification_requests;
CREATE TRIGGER trg_hist_verification_requests AFTER UPDATE OR DELETE ON verification_requests
  FOR EACH ROW EXECUTE FUNCTION fn_record_history('id');

COMMIT;

