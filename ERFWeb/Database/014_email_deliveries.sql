-- =====================================================================
--  ERFWeb — Phase 7: email the R47 PDF (014_email_deliveries.sql)
--  * email_deliveries: one row per email about an expense report, either a manual "Email R47" or a
--    workflow event (filed, approved, fully approved, returned, rejected). The unique
--    (sender_user_id, idempotency_key) pair is claimed before SMTP is called, so a retried request
--    or a replayed workflow event never emails twice. This is the report's email "sent status".
--  * Addresses, subject, body and the PDF are NOT stored; recipients are re-read from users.email.
--  * Status: Sending -> Sent | Failed (server refused; may be retried) | Unconfirmed (no answer;
--    never resent under the same key).
--  Idempotent: safe to re-run. Run after 001..013.
-- =====================================================================
BEGIN;

CREATE TABLE IF NOT EXISTS email_deliveries (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_user_id       bigint NOT NULL REFERENCES users (id),
  idempotency_key      character varying(100) NOT NULL,
  report_id            uuid NOT NULL,
  kind                 character varying(40) NOT NULL,                -- R47 | ReportFiled | ReportApproved | ...
  recipient_count      integer NOT NULL,
  status               character varying(16) NOT NULL,                -- Sending | Sent | Failed | Unconfirmed
  smtp_status_code     integer,
  attempts             integer NOT NULL DEFAULT 1,
  created_at           timestamp with time zone NOT NULL DEFAULT now(),
  completed_at         timestamp with time zone
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_email_deliveries_expense_reports_report_id') THEN
    ALTER TABLE email_deliveries
      ADD CONSTRAINT fk_email_deliveries_expense_reports_report_id
      FOREIGN KEY (report_id) REFERENCES expense_reports (id) ON DELETE CASCADE;
  END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS ix_email_deliveries_sender_user_id_idempotency_key
  ON email_deliveries (sender_user_id, idempotency_key);
CREATE INDEX IF NOT EXISTS ix_email_deliveries_report_id_created_at ON email_deliveries (report_id, created_at);

COMMIT;

