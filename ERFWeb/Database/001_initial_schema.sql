-- =====================================================================
--  ERFWeb — PostgreSQL schema (001_initial_schema.sql)
--  Matches the EF Core model in ErfDbContext (Npgsql, snake_case).
--  Requires PostgreSQL 13+ (gen_random_uuid(), jsonb).
--  Idempotent: safe to re-run. Run against an empty database, e.g.:
--    createdb erfweb
--    psql -d erfweb -f 001_initial_schema.sql
-- =====================================================================
BEGIN;

-- ---------- Reference / identity ----------
CREATE TABLE IF NOT EXISTS departments (
  id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code  text,
  name  text NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_departments_code ON departments (code);

CREATE TABLE IF NOT EXISTS users (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username          text NOT NULL,
  password_hash     text NOT NULL,                         -- PBKDF2: {iterations}.{saltB64}.{hashB64}
  full_name         text NOT NULL,
  position          text,
  email             text,
  mobile_no         text,
  department_id     bigint REFERENCES departments (id),
  role              character varying(16) NOT NULL DEFAULT 'Employee',   -- Employee | Manager | Finance | Admin
  signature         bytea,
  work_with_enabled boolean NOT NULL DEFAULT false,
  is_active         boolean NOT NULL DEFAULT true,
  created_at        timestamp with time zone NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_users_username      ON users (username);
CREATE INDEX        IF NOT EXISTS ix_users_department_id ON users (department_id);

-- Ordered approval chain per employee (who approves their reports, in what order)
CREATE TABLE IF NOT EXISTS approval_routes (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_user_id bigint  NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  step_order       integer NOT NULL,
  approver_user_id bigint  NOT NULL REFERENCES users (id) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_approval_routes_employee_user_id_step_order ON approval_routes (employee_user_id, step_order);
CREATE INDEX        IF NOT EXISTS ix_approval_routes_approver_user_id            ON approval_routes (approver_user_id);

-- Department signatories printed on the R47 (initials + signature images)
CREATE TABLE IF NOT EXISTS department_signatories (
  department_id      bigint PRIMARY KEY REFERENCES departments (id),
  endorser_initials  text,
  reviewer_initials  text,
  approver_initials  text,
  endorser_signature bytea,
  reviewer_signature bytea,
  approver_signature bytea
);

CREATE TABLE IF NOT EXISTS employee_rates (
  user_id        bigint PRIMARY KEY REFERENCES users (id),
  transport_rate numeric(14,2) NOT NULL DEFAULT 0,
  breakfast_rate numeric(14,2) NOT NULL DEFAULT 0,
  lunch_rate     numeric(14,2) NOT NULL DEFAULT 0,
  dinner_rate    numeric(14,2) NOT NULL DEFAULT 0,
  ot_meal_rate   numeric(14,2) NOT NULL DEFAULT 0
);

-- ---------- Expense reports ----------
CREATE TABLE IF NOT EXISTS expense_reports (
  id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  reference_no          text,
  employee_user_id      bigint NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  report_type           character varying(32) NOT NULL,                   -- RevolvingFund | CashAdvanceLiquidation | Reimbursement
  purpose               text,
  date_from             date,
  date_to               date,
  status                character varying(16) NOT NULL DEFAULT 'New',     -- New | ForApproval | Returned | Approved
  revolving_fund_amount numeric(14,2) NOT NULL DEFAULT 0,
  current_cycle         integer NOT NULL DEFAULT 1,
  filed_at              timestamp with time zone,
  approved_at           timestamp with time zone,
  cancel_note           text,
  sent_status           boolean NOT NULL DEFAULT false,
  created_at            timestamp with time zone NOT NULL DEFAULT now(),
  updated_at            timestamp with time zone NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_expense_reports_reference_no     ON expense_reports (reference_no);
CREATE INDEX        IF NOT EXISTS ix_expense_reports_employee_user_id ON expense_reports (employee_user_id);
CREATE INDEX        IF NOT EXISTS ix_expense_reports_status           ON expense_reports (status);

-- 1:1 with expense_reports
CREATE TABLE IF NOT EXISTS cash_advances (
  report_id          uuid PRIMARY KEY REFERENCES expense_reports (id) ON DELETE CASCADE,
  amount             numeric(14,2) NOT NULL DEFAULT 0,
  advance_date       date,
  reference_document text,
  reference_no       text,
  balance_to         character varying(16) NOT NULL DEFAULT 'EMPLOYEE'
);

CREATE TABLE IF NOT EXISTS expense_lines (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id        uuid NOT NULL REFERENCES expense_reports (id) ON DELETE CASCADE,
  transaction_date date NOT NULL,
  particulars      text,
  work_with        text,
  invoice_or_no    text,
  expense_type     character varying(16) NOT NULL DEFAULT 'Local',        -- Local | Foreign
  category         character varying(24) NOT NULL,                        -- Meals | Transportation | Toll | Parking | Others | Representation
  amount           numeric(14,2) NOT NULL DEFAULT 0,
  vat_amount       numeric(14,2) NOT NULL DEFAULT 0,
  total_amount     numeric(14,2) NOT NULL DEFAULT 0,
  location         text,
  service_number   text,
  instrument       text,
  serial_number    text,
  is_perdiem       boolean NOT NULL DEFAULT false,
  multiplier       integer NOT NULL DEFAULT 1,
  minus_days       integer,
  total_days       integer,
  computation      text,
  remarks          text,
  sort_order       integer NOT NULL DEFAULT 0,
  is_active        boolean NOT NULL DEFAULT true,
  created_at       timestamp with time zone NOT NULL DEFAULT now(),
  updated_at       timestamp with time zone NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_expense_lines_report_id_sort_order ON expense_lines (report_id, sort_order);

CREATE TABLE IF NOT EXISTS expense_meal_items (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  expense_line_id  bigint NOT NULL REFERENCES expense_lines (id) ON DELETE CASCADE,
  meal_type        text,                                                 -- Breakfast | Lunch | Dinner | OT
  paid_for         text,
  paid_employee_id bigint
);
CREATE INDEX IF NOT EXISTS ix_expense_meal_items_expense_line_id ON expense_meal_items (expense_line_id);

CREATE TABLE IF NOT EXISTS expense_transport_items (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  expense_line_id bigint NOT NULL REFERENCES expense_lines (id) ON DELETE CASCADE,
  fare_from       text,
  fare_to         text,
  fare_amount     numeric(14,2) NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS ix_expense_transport_items_expense_line_id ON expense_transport_items (expense_line_id);

-- ---------- Approval workflow ----------
CREATE TABLE IF NOT EXISTS approval_steps (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id        uuid    NOT NULL REFERENCES expense_reports (id) ON DELETE CASCADE,
  cycle            integer NOT NULL DEFAULT 1,
  step_order       integer NOT NULL,
  approver_user_id bigint  NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  status           character varying(16) NOT NULL DEFAULT 'Pending',     -- Pending | Approved | Returned | Superseded
  acted_at         timestamp with time zone,
  signature        bytea,
  note             text
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_approval_steps_report_id_cycle_step_order ON approval_steps (report_id, cycle, step_order);
CREATE INDEX        IF NOT EXISTS ix_approval_steps_report_id_status           ON approval_steps (report_id, status);
CREATE INDEX        IF NOT EXISTS ix_approval_steps_approver_user_id           ON approval_steps (approver_user_id);

-- ---------- Finance ----------
CREATE TABLE IF NOT EXISTS finance_tracking (
  report_id                  uuid PRIMARY KEY REFERENCES expense_reports (id) ON DELETE CASCADE,
  status                     character varying(24) NOT NULL DEFAULT 'Pending',   -- Pending | ReceiptsReceived
  physical_receipts_received boolean NOT NULL DEFAULT false,
  received_by_user_id        bigint,
  received_at                timestamp with time zone,
  remarks                    text
);

-- ---------- Attachments / notifications ----------
CREATE TABLE IF NOT EXISTS receipt_attachments (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id           uuid   NOT NULL REFERENCES expense_reports (id) ON DELETE CASCADE,
  file_name           text   NOT NULL,
  content_type        text   NOT NULL,
  size_bytes          bigint NOT NULL,
  content             bytea  NOT NULL,
  uploaded_by_user_id bigint NOT NULL,
  uploaded_at         timestamp with time zone NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_receipt_attachments_report_id ON receipt_attachments (report_id);

CREATE TABLE IF NOT EXISTS reminder_deliveries (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id       uuid    NOT NULL REFERENCES expense_reports (id) ON DELETE CASCADE,
  step_id         bigint,
  reminder_number integer NOT NULL,
  channel         character varying(16) NOT NULL,                        -- Email | SMS
  audience        character varying(16) NOT NULL,                        -- Approver | Employee
  status          character varying(16) NOT NULL,                        -- Sent | Failed | Skipped
  sent_at         timestamp with time zone,
  failure_code    text
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_reminder_deliveries_unique
  ON reminder_deliveries (report_id, step_id, reminder_number, channel, audience);

-- ---------- Security / audit ----------
CREATE TABLE IF NOT EXISTS login_security (
  username        character varying(64) PRIMARY KEY,
  failed_attempts integer NOT NULL DEFAULT 0,
  lockout_until   timestamp with time zone,
  last_attempt_at timestamp with time zone
);

CREATE TABLE IF NOT EXISTS workflow_audit (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  correlation_id uuid,
  report_id      uuid,
  event          character varying(64) NOT NULL,                         -- Filed | ManagerApproved | ManagerReturned | PhysicalReceiptsReceived | ...
  actor_user_id  bigint,
  occurred_at    timestamp with time zone NOT NULL DEFAULT now(),
  detail         jsonb
);
CREATE INDEX IF NOT EXISTS ix_workflow_audit_report_id ON workflow_audit (report_id);

-- Row-level history, written by the triggers below on the high-churn tables only
CREATE TABLE IF NOT EXISTS record_history (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_name  character varying(64) NOT NULL,
  row_pk      character varying(64) NOT NULL,
  operation   character varying(1)  NOT NULL,                             -- U = update, D = delete
  changed_at  timestamp with time zone NOT NULL DEFAULT now(),
  changed_by  bigint,                                                    -- from SET LOCAL app.current_user_id
  old_data    jsonb,
  new_data    jsonb
);
CREATE INDEX IF NOT EXISTS ix_record_history_table_name_row_pk ON record_history (table_name, row_pk);

-- ---------- History trigger function ----------
CREATE OR REPLACE FUNCTION fn_record_history() RETURNS trigger AS $$
DECLARE
  v_user bigint := NULLIF(current_setting('app.current_user_id', true), '')::bigint;
BEGIN
  IF (TG_OP = 'UPDATE') THEN
    IF to_jsonb(NEW) IS DISTINCT FROM to_jsonb(OLD) THEN
      INSERT INTO record_history(table_name, row_pk, operation, changed_by, old_data, new_data)
      VALUES (TG_TABLE_NAME, (to_jsonb(OLD)->>TG_ARGV[0]), 'U', v_user, to_jsonb(OLD), to_jsonb(NEW));
    END IF;
    RETURN NEW;
  ELSIF (TG_OP = 'DELETE') THEN
    INSERT INTO record_history(table_name, row_pk, operation, changed_by, old_data, new_data)
    VALUES (TG_TABLE_NAME, (to_jsonb(OLD)->>TG_ARGV[0]), 'D', v_user, to_jsonb(OLD), NULL);
    RETURN OLD;
  END IF;
  RETURN NULL;
END;
$$ LANGUAGE plpgsql;

-- Attach ONLY to the important, constantly-changing tables (argument = that table's PK column)
DROP TRIGGER IF EXISTS trg_hist_expense_reports  ON expense_reports;
DROP TRIGGER IF EXISTS trg_hist_expense_lines    ON expense_lines;
DROP TRIGGER IF EXISTS trg_hist_approval_steps   ON approval_steps;
DROP TRIGGER IF EXISTS trg_hist_finance_tracking ON finance_tracking;
DROP TRIGGER IF EXISTS trg_hist_cash_advances    ON cash_advances;

CREATE TRIGGER trg_hist_expense_reports  AFTER UPDATE OR DELETE ON expense_reports
  FOR EACH ROW EXECUTE FUNCTION fn_record_history('id');
CREATE TRIGGER trg_hist_expense_lines    AFTER UPDATE OR DELETE ON expense_lines
  FOR EACH ROW EXECUTE FUNCTION fn_record_history('id');
CREATE TRIGGER trg_hist_approval_steps   AFTER UPDATE OR DELETE ON approval_steps
  FOR EACH ROW EXECUTE FUNCTION fn_record_history('id');
CREATE TRIGGER trg_hist_finance_tracking AFTER UPDATE OR DELETE ON finance_tracking
  FOR EACH ROW EXECUTE FUNCTION fn_record_history('report_id');
CREATE TRIGGER trg_hist_cash_advances    AFTER UPDATE OR DELETE ON cash_advances
  FOR EACH ROW EXECUTE FUNCTION fn_record_history('report_id');

COMMIT;
