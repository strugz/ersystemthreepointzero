CREATE TABLE IF NOT EXISTS sites (
  id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code      character varying(32)  NOT NULL,
  name      character varying(200) NOT NULL,
  is_active boolean NOT NULL DEFAULT true
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_sites_code ON sites (code);

-- ---------- Rules (key/value; the application supplies defaults for missing keys) ----------
CREATE TABLE IF NOT EXISTS app_settings (
  key                character varying(64) NOT NULL PRIMARY KEY,
  value              text NOT NULL,
  updated_by_user_id bigint REFERENCES users (id) ON DELETE SET NULL,
  updated_at         timestamp with time zone NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_app_settings_updated_by_user_id ON app_settings (updated_by_user_id);

-- ---------- Accounts ----------
ALTER TABLE users ADD COLUMN IF NOT EXISTS job_grade      character varying(32);
ALTER TABLE users ADD COLUMN IF NOT EXISTS cost_center_id bigint REFERENCES cost_centers (id);
CREATE INDEX IF NOT EXISTS ix_users_cost_center_id ON users (cost_center_id);

-- Additive roles with dual approval (spec 9.7, 9.8). Employee is implicit and never stored.
CREATE TABLE IF NOT EXISTS user_roles (
  user_id                  bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  role                     character varying(32) NOT NULL,   -- SignatoryLevel1 | SignatoryLevel2 | Finance | ExpenseVerifier | SystemAdministrator | BusinessOwner
  status                   character varying(24) NOT NULL DEFAULT 'PendingActivation',  -- PendingActivation | Active | Revoked
  granted_by_user_id       bigint REFERENCES users (id),
  granted_at               timestamp with time zone NOT NULL DEFAULT now(),
  countersigned_by_user_id bigint REFERENCES users (id),
  countersigned_at         timestamp with time zone,
  revoked_by_user_id       bigint REFERENCES users (id),
  revoked_at               timestamp with time zone,
  is_bootstrap             boolean NOT NULL DEFAULT false,
  note                     character varying(500),
  PRIMARY KEY (user_id, role),
  CONSTRAINT ck_user_roles_no_self_elevation CHECK (granted_by_user_id IS DISTINCT FROM user_id)
);
CREATE INDEX IF NOT EXISTS ix_user_roles_role_status             ON user_roles (role, status);
CREATE INDEX IF NOT EXISTS ix_user_roles_granted_by_user_id       ON user_roles (granted_by_user_id);
CREATE INDEX IF NOT EXISTS ix_user_roles_countersigned_by_user_id ON user_roles (countersigned_by_user_id);
CREATE INDEX IF NOT EXISTS ix_user_roles_revoked_by_user_id       ON user_roles (revoked_by_user_id);

