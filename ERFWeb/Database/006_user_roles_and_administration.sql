-- ---------- Master data ----------
ALTER TABLE departments ADD COLUMN IF NOT EXISTS is_active boolean NOT NULL DEFAULT true;

CREATE TABLE IF NOT EXISTS cost_centers (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          character varying(32)  NOT NULL,
  name          character varying(200) NOT NULL,
  department_id bigint REFERENCES departments (id),
  is_active     boolean NOT NULL DEFAULT true
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_cost_centers_code          ON cost_centers (code);
CREATE INDEX        IF NOT EXISTS ix_cost_centers_department_id ON cost_centers (department_id);

CREATE TABLE IF NOT EXISTS currencies (
  code       character varying(3)   NOT NULL PRIMARY KEY,
  name       character varying(100) NOT NULL,
  is_default boolean NOT NULL DEFAULT false,
  is_active  boolean NOT NULL DEFAULT true
);
