-- Migrate the legacy single role column, if it still exists, into user_roles. Legacy roles were
-- never countersigned, so they are activated as bootstrap grants with no granter (the CHECK above
-- allows NULL). Manager -> Signatory Level 1; Admin -> System Administrator; Finance -> Finance.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'users' AND column_name = 'role') THEN
    INSERT INTO user_roles (user_id, role, status, granted_at, countersigned_at, is_bootstrap, note)
    SELECT u.id,
           CASE u.role WHEN 'Manager' THEN 'SignatoryLevel1' WHEN 'Admin' THEN 'SystemAdministrator' ELSE u.role END,
           'Active', now(), now(), true, 'Migrated from users.role by 006'
    FROM users u
    WHERE u.role IN ('Manager', 'Finance', 'Admin')
    ON CONFLICT (user_id, role) DO NOTHING;

    ALTER TABLE users DROP COLUMN role;
  END IF;
END $$;

